PASS_THRESHOLD = 35  # 카페는 지식iN보다 글이 짧을 수 있으므로 35점 이상 합격


class AuraCafeFilter:
    """💖 Aura 네이버 5대 카페 전용 정밀 필터"""

    def __init__(self, pass_threshold: int = PASS_THRESHOLD):
        self.pass_threshold = pass_threshold
        self.whitelist = AURA_CAFE_WHITELIST
        self.blacklist = AURA_CAFE_BLACKLIST
        self.anchors = AURA_CAFE_ANCHORS

    def evaluate_post(self, title: str, content: str = "", cafe_name: str = "") -> Tuple[int, bool, str, List[str], List[str]]:
        """
        카페 게시글 제목과 본문을 검증하여 합격 여부 및 점수 도출
        반환: (score: int, is_passed: bool, reason: str, matched_white: list, matched_black: list)
        """
        title = title or ""
        content = content or ""
        full_text = f"{title} {content}"
        text_lower = full_text.lower()

        matched_black = [bl for bl in self.blacklist if bl.lower() in text_lower]
        if matched_black:
            return 0, False, f"블랙리스트 차단: {', '.join(matched_black[:3])}", [], matched_black

        # 필수 앵커 키워드 포함 여부 검증
        matched_anchors = [ac for ac in self.anchors if ac.lower() in text_lower]
        if not matched_anchors:
            return 0, False, "연애/만남 핵심 앵커 키워드 부재", [], []

        # 화이트리스트 점수 합산
        score = 0
        matched_white = []
        for kw, weight in self.whitelist.items():
            cnt = len(re.findall(re.escape(kw.lower()), text_lower))
            if cnt > 0:
                matched_white.append(kw)
                # 최대 2회까지 가중치 합산
                score += weight * min(cnt, 2)

        # 제목에 앵커가 포함되어 있으면 가산점 (+15점)
        for ac in self.anchors:
            if ac.lower() in title.lower():
                score += 15
                break

        # 본문 분량 가산점
        if len(content) >= 50:
            score += 5
        if len(content) >= 150:
            score += 5

        score = min(score, 100)
        is_passed = score >= self.pass_threshold
        reason = f"적합도 {score}점 (합격)" if is_passed else f"적합도 {score}점 (기준점 {self.pass_threshold}점 미달)"

        return score, is_passed, reason, matched_white, []


