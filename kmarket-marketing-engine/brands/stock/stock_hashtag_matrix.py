    @classmethod
    def fetch_live_trend_keywords(cls) -> List[str]:
        """🟢 코스피·코스닥 국내 증시 퀀트 실시간 검색어(Naver AC API) 수집 (무관한 일반 검색어 100% 원천 차단)"""
        trends = []
        import urllib.request
        import urllib.parse
        import json

        # 🟢 네이버 실시간 주식/증시/수급 검색어 (Naver AC API)
        naver_seeds = ["코스피 주도주", "체결강도", "외국인 순매수", "주식 퀀트", "당일 급등주"]
        for seed in naver_seeds:
            try:
                encoded_q = urllib.parse.quote(seed)
                url_nv = f"https://ac.search.naver.com/nx/ac?q={encoded_q}&st=100&frm=nv&ans=2&r_format=json"
                req_nv = urllib.request.Request(url_nv, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"})
                with urllib.request.urlopen(req_nv, timeout=2.5) as resp:
                    data = json.loads(resp.read().decode("utf-8", errors="ignore"))
                    items = data.get("items", [[]])[0]
                    for it in items:
                        if isinstance(it, list) and len(it) > 0:
                            w = it[0].strip().replace(" ", "").replace("#", "")
                            if w and len(w) < 14 and f"#{w}" not in trends:
                                trends.append(f"#{w}")
                        if len(trends) >= 8:
                            break
            except Exception:
                pass
            if len(trends) >= 8:
                break

        fallback = ["#코스피주도주", "#국내증시", "#체결강도", "#외국인순매수", "#퀀트투자", "#특징주"]
        for fb in fallback:
            if fb not in trends and len(trends) < 6:
                trends.append(fb)

        return trends[:6]

    @classmethod
    def get_rich_viral_hashtags(cls, topic_id: int = 1, count: int = 15) -> List[str]:
        """
        주제별 1:1 고유 롱테일 + 브랜드 공식 태그 + 실시간 구글/네이버 트렌드 결합 (최대 15개)
        """
        tags: List[str] = []

        # 1. 🏷️ 브랜드 공식 핵심 태그 (불변 철칙)
        tags.extend(cls.BRAND_TAGS[:2])  # #스톡마스터AI, #StockMasterAI

        # 2. 🎯 주제별 1:1 고유 롱테일 태그 (100% 매칭)
        longtail = cls.TOPIC_LONGTAIL_MAP.get(topic_id, cls.TOPIC_LONGTAIL_MAP[1])
        for t in longtail:
            if t not in tags:
                tags.append(t)

        # 3. 🌐 실시간 구글 & 네이버 급상승 트렌드 키워드 결합
        live_trends = cls.fetch_live_trend_keywords()
        for lt in live_trends:
            if lt not in tags:
                tags.append(lt)
            if len(tags) >= count:
                break

        # 4. 공통 퀀트 태그 보충
        common_fillers = ["#주식투자", "#재테크", "#국내주식", "#직장인투자", "#주식공부", "#주린이"]
        for cf in common_fillers:
            if len(tags) >= count:
                break
            if cf not in tags:
                tags.append(cf)

        return tags[:count]

